"use client";

import { useEffect, useState } from "react";
import type {
  Scenario,
  BenchmarkResult,
  DetectorEntry,
  Attestation,
  VerifyResult,
} from "@/lib/core";

type RunResponse = {
  seed: number;
  count: number;
  fraction: number;
  provider: string;
  scenarios: Scenario[];
  benchmark: BenchmarkResult;
  metering?: { metered: boolean; reason?: string };
};

const pct = (x: number) => `${(x * 100).toFixed(0)}%`;
const usd = (nano: number) => `$${(nano / 1e9).toFixed(6)}`;
const spoofingOf = (d: DetectorEntry) =>
  d.metrics.by_type.spoofing ?? { caught: 0, total: 0 };

export default function Home() {
  const [seed, setSeed] = useState(7);
  const [count, setCount] = useState(10);
  const [fraction, setFraction] = useState(0.4);
  const [provider, setProvider] = useState<"stub" | "flock">("stub");

  const [data, setData] = useState<RunResponse | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [selectedMiss, setSelectedMiss] = useState<string | null>(null);

  async function runBenchmark() {
    setLoading(true);
    setError(null);
    setSelectedMiss(null);
    try {
      const res = await fetch("/api/run", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ seed, count, fraction, provider }),
      });
      const json = await res.json();
      if (!res.ok) throw new Error(json.stderr || json.error || "run failed");
      setData(json as RunResponse);
    } catch (e) {
      setError((e as Error).message);
      setData(null);
    } finally {
      setLoading(false);
    }
  }

  const scenarioById = (id: string) =>
    data?.scenarios.find((s) => s.scenario_id === id);

  return (
    <main className="mx-auto max-w-6xl px-5 py-10">
      <Header />

      <MarketReference />

      <Controls
        seed={seed} setSeed={setSeed}
        count={count} setCount={setCount}
        fraction={fraction} setFraction={setFraction}
        provider={provider} setProvider={setProvider}
        loading={loading} onRun={runBenchmark}
      />

      {error && (
        <div className="mt-6 rounded-lg border border-red-500/40 bg-red-500/10 p-4 text-sm text-red-200">
          <span className="font-semibold">Core error:</span>{" "}
          <span className="mono">{error}</span>
        </div>
      )}

      {data && (
        <>
          <section className="mt-8 grid grid-cols-1 gap-4 md:grid-cols-2">
            {data.benchmark.detectors.map((d) => (
              <DetectorCard key={d.detector_id} d={d} />
            ))}
          </section>

          <RunMeta benchmark={data.benchmark} provider={data.provider} metering={data.metering} />

          <MissPanel
            detectors={data.benchmark.detectors}
            selected={selectedMiss}
            onSelect={setSelectedMiss}
            scenario={selectedMiss ? scenarioById(selectedMiss) : undefined}
          />

          <WalrusPanel seed={seed} count={count} fraction={fraction} />
        </>
      )}

      <ModelCatalog provider={provider} />

      <footer className="mt-16 border-t border-white/5 pt-6 text-xs text-white/30">
        ProvingGround — validation infrastructure for market-surveillance models. Core
        generated by Codeplain; head-to-head via FLock; tamper-evident record on Walrus.
      </footer>
    </main>
  );
}

type MarketRef = {
  pool: string; mid: number; best_bid: number; best_ask: number;
  spread: number; spread_bps: number; bid_depth: number; ask_depth: number;
  source: string; error?: string;
};

function MarketReference() {
  const [m, setM] = useState<MarketRef | null>(null);
  const [err, setErr] = useState<string | null>(null);

  useEffect(() => {
    let active = true;
    fetch("/api/market")
      .then((r) => r.json())
      .then((j) => { if (!active) return; if (j.error) setErr(j.error); else setM(j as MarketRef); })
      .catch((e) => active && setErr(String(e)));
    return () => { active = false; };
  }, []);

  return (
    <div className="mt-6 rounded-xl border border-white/10 bg-white/[0.02] px-5 py-3">
      <div className="flex flex-wrap items-center gap-x-6 gap-y-1 text-xs">
        <span className="flex items-center gap-2 text-white/50">
          <span className="inline-block h-1.5 w-1.5 rounded-full bg-emerald-400" />
          live market reference · <span className="mono text-white/70">DeepBook SUI/USDC</span>
        </span>
        {m ? (
          <>
            <span className="text-white/40">mid <span className="mono text-white/80">${m.mid.toFixed(5)}</span></span>
            <span className="text-white/40">spread <span className="mono text-white/80">{m.spread_bps.toFixed(1)} bps</span></span>
            <span className="text-white/40">depth <span className="mono text-white/80">{Math.round(m.bid_depth).toLocaleString()} bid / {Math.round(m.ask_depth).toLocaleString()} ask</span></span>
            <span className="ml-auto text-white/25">scenarios are calibrated against this live book</span>
          </>
        ) : (
          <span className="text-white/30">{err ? "DeepBook unavailable" : "loading live book…"}</span>
        )}
      </div>
    </div>
  );
}


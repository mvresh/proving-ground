function WalrusPanel({ seed, count, fraction }: { seed: number; count: number; fraction: number }) {
  const [store, setStore] = useState<"stub" | "walrus">("stub");
  const [att, setAtt] = useState<Attestation | null>(null);
  const [verify, setVerify] = useState<{ result: VerifyResult; exitCode: number } | null>(null);
  const [busy, setBusy] = useState<"" | "attest" | "verify">("");
  const [err, setErr] = useState<string | null>(null);

  async function doAttest() {
    setBusy("attest"); setErr(null); setVerify(null); setAtt(null);
    try {
      const res = await fetch("/api/attest", {
        method: "POST", headers: { "content-type": "application/json" },
        body: JSON.stringify({ seed, count, fraction, store }),
      });
      const json = await res.json();
      if (!res.ok) throw new Error(json.stderr || json.error || "attest failed");
      setAtt(json.attestation as Attestation);
    } catch (e) { setErr((e as Error).message); } finally { setBusy(""); }
  }

  async function doVerify() {
    if (!att) return;
    setBusy("verify"); setErr(null);
    try {
      const res = await fetch("/api/verify", {
        method: "POST", headers: { "content-type": "application/json" },
        body: JSON.stringify({ attestation: att, store }),
      });
      const json = await res.json();
      if (!json.result) throw new Error(json.error || "verify failed");
      setVerify({ result: json.result as VerifyResult, exitCode: json.exitCode ?? -1 });
    } catch (e) { setErr((e as Error).message); } finally { setBusy(""); }
  }

  return (
    <section className="mt-8 rounded-xl border border-white/10 bg-white/[0.03] p-5">
      <h2 className="text-lg font-semibold">Tamper-evident record (Walrus)</h2>
      <p className="mt-1 text-sm text-white/50">
        Write the scored run to a content-addressed blob store, then verify by re-fetching and
        recomputing the hash. If the bytes were altered, verification fails — the catch-rate
        claim is provable, not just asserted.
      </p>

      <div className="mt-4 flex flex-wrap items-center gap-3">
        <select value={store} onChange={(e) => setStore(e.target.value as "stub" | "walrus")}
          className="rounded-lg border border-white/12 bg-[#0d1117] px-3 py-2 text-sm">
          <option value="stub">stub (offline)</option>
          <option value="walrus">walrus (live testnet)</option>
        </select>
        <button onClick={doAttest} disabled={busy !== ""}
          className="rounded-lg bg-purple-500 px-4 py-2 text-sm font-semibold text-slate-950 transition hover:bg-purple-400 disabled:opacity-50">
          {busy === "attest" ? "Attesting…" : "Attest run"}
        </button>
        <button onClick={doVerify} disabled={!att || busy !== ""}
          className="rounded-lg border border-white/20 px-4 py-2 text-sm font-semibold transition hover:border-white/40 disabled:opacity-40">
          {busy === "verify" ? "Verifying…" : "Verify"}
        </button>
      </div>

      {err && (
        <div className="mt-4 rounded-lg border border-red-500/40 bg-red-500/10 p-3 text-xs text-red-200">
          <span className="mono">{err}</span>
        </div>
      )}

      {att && (
        <div className="mt-4 space-y-1.5 rounded-lg border border-white/10 bg-black/30 p-4 text-xs">
          <Row k="store" v={att.store} />
          <Row k="run_id" v={att.run_id} />
          <Row k="blob_id" v={att.blob_id} />
          <Row k="content_sha256" v={att.content_sha256} />
        </div>
      )}

      {verify && (
        <div className={`mt-3 flex items-center gap-3 rounded-lg border p-4 text-sm ${
          verify.result.verified
            ? "border-emerald-500/40 bg-emerald-500/10 text-emerald-200"
            : "border-red-500/40 bg-red-500/10 text-red-200"
        }`}>
          <span className="text-xl">{verify.result.verified ? "✓" : "✗"}</span>
          <div>
            <div className="font-semibold">
              {verify.result.verified ? "Verified — bytes are intact" : "TAMPER DETECTED — hash mismatch"}
            </div>
            <div className="mono mt-1 text-[11px] opacity-80">
              computed {verify.result.computed_sha256.slice(0, 16)}… {verify.result.verified ? "==" : "≠"}{" "}
              expected {verify.result.expected_sha256.slice(0, 16)}…
            </div>
          </div>
        </div>
      )}
    </section>
  );
}

function Row({ k, v }: { k: string; v: string }) {
  return (
    <div className="flex gap-3">
      <span className="w-28 shrink-0 text-white/40">{k}</span>
      <span className="mono break-all text-white/80">{v}</span>
    </div>
  );
}

function ModelCatalog({ provider }: { provider: "stub" | "flock" }) {
  const [models, setModels] = useState<string[]>([]);
  const [err, setErr] = useState<string | null>(null);

  useEffect(() => {
    let active = true;
    fetch(`/api/models?provider=${provider}`)
      .then((r) => r.json())
      .then((j) => {
        if (!active) return;
        setModels(j.models ?? []);
        setErr(j.error ?? null);
      })
      .catch((e) => active && setErr(String(e)));
    return () => { active = false; };
  }, [provider]);

  return (
    <section className="mt-8 rounded-xl border border-white/10 bg-white/[0.02] p-5">
      <h2 className="text-sm font-semibold text-white/70">
        Model catalog <span className="mono text-white/40">({provider})</span>
      </h2>
      {err ? (
        <div className="mt-2 text-xs text-amber-300/80">
          {provider === "flock"
            ? "FLock unavailable (account may need a top-up). The stub provider keeps the demo fully offline."
            : err}
        </div>
      ) : (
        <div className="mt-3 flex flex-wrap gap-2">
          {models.map((m) => (
            <span key={m} className="mono rounded-full border border-white/10 bg-white/[0.04] px-2.5 py-1 text-[11px] text-white/70">
              {m}
            </span>
          ))}
        </div>
      )}
    </section>
  );
}
